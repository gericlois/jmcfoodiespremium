-- JMC Foodies Basics — grocery credit-line ordering system.
-- Shares the `users`/`admins` login tables above; a user "joins" Basics by
-- getting a row here (application_status starts 'pending', admin approves).
CREATE TABLE basics_members (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT NOT NULL UNIQUE,
    employer_name VARCHAR(150) NOT NULL,
    employer_contact VARCHAR(100) DEFAULT NULL,
    position VARCHAR(100) DEFAULT NULL,
    application_status ENUM('pending','approved','denied') NOT NULL DEFAULT 'pending',
    membership_status ENUM('active','suspended','dormant','terminated') NOT NULL DEFAULT 'active',
    weekly_credit_limit DECIMAL(10,2) NOT NULL DEFAULT 0,
    emergency_credit_limit DECIMAL(10,2) NOT NULL DEFAULT 0,
    offense_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
    consecutive_on_time_payments INT UNSIGNED NOT NULL DEFAULT 0,
    credit_limit_frozen TINYINT(1) NOT NULL DEFAULT 0,
    suspended_until DATE DEFAULT NULL,
    last_activity_at TIMESTAMP NULL DEFAULT NULL,
    reviewed_by INT DEFAULT NULL,
    reviewed_at TIMESTAMP NULL DEFAULT NULL,
    admin_notes VARCHAR(255) DEFAULT NULL,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES basics_users(id) ON DELETE CASCADE,
    FOREIGN KEY (reviewed_by) REFERENCES basics_admins(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- KYC documents (2 valid IDs, Barangay Clearance, Application Form, COE).
-- Deliberately NOT served the way product images are — see uploads/basics_kyc/
-- .htaccess and basics/admin/kyc_view.php. These are government ID scans.
CREATE TABLE basics_kyc_documents (
    id INT AUTO_INCREMENT PRIMARY KEY,
    member_id INT NOT NULL,
    doc_type ENUM('valid_id_1','valid_id_2','barangay_clearance','membership_application_form','membership_application_form_back','certificate_of_employment') NOT NULL,
    file_path VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (member_id) REFERENCES basics_members(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Sari-sari-store convenience goods catalog, 613 SKUs across 8 categories
-- (JMC_Foodies_Basics_*_Masterlist.pdf). srp is seeded at the low end of each
-- masterlist's price range; admin adjusts individual items via
-- basics/admin/product_edit.php.
CREATE TABLE basics_products (
    id INT AUTO_INCREMENT PRIMARY KEY,
    sku VARCHAR(20) NOT NULL UNIQUE,
    category ENUM('Rice','Food Essentials','Cooking Products','Beverages','Homecare','Personal Care','Palengke Items','Frozen Meat Products','Bread & Snacks') NOT NULL,
    name VARCHAR(150) NOT NULL,
    unit VARCHAR(50) NOT NULL,
    srp DECIMAL(10,2) NOT NULL DEFAULT 0,
    image VARCHAR(255) DEFAULT NULL,
    status ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- Weekly ordering windows (Mon-Thu order, Fri cutoff, Sat-Sun payment,
-- Sun/Mon delivery). `status` is a display cache only — window-gating logic
-- always recomputes from the date columns against today's date.
CREATE TABLE basics_cycles (
    id INT AUTO_INCREMENT PRIMARY KEY,
    label VARCHAR(50) NOT NULL,
    order_open_date DATE NOT NULL UNIQUE,
    order_cutoff_date DATE NOT NULL,
    payment_start_date DATE NOT NULL,
    payment_due_date DATE NOT NULL,
    delivery_date DATE NOT NULL,
    status ENUM('upcoming','ordering','cutoff','payment','delivered','closed') NOT NULL DEFAULT 'upcoming',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- One cart/order per member per cycle (multi-item, unlike Wellness's
-- single-product orders table).
CREATE TABLE basics_orders (
    id INT AUTO_INCREMENT PRIMARY KEY,
    member_id INT NOT NULL,
    cycle_id INT NOT NULL,
    total_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
    -- status flips to 'paid' automatically (basics_record_payment(),
    -- basics/includes/functions.php) once payments cover total_amount.
    status ENUM('draft','pending','paid','delivered','cancelled') NOT NULL DEFAULT 'draft',
    placed_at TIMESTAMP NULL DEFAULT NULL,
    delivered_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (member_id) REFERENCES basics_members(id) ON DELETE CASCADE,
    FOREIGN KEY (cycle_id) REFERENCES basics_cycles(id) ON DELETE RESTRICT,
    UNIQUE KEY (member_id, cycle_id)
) ENGINE=InnoDB;

CREATE TABLE basics_order_items (
    id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    unit_price DECIMAL(10,2) NOT NULL,
    line_total DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (order_id) REFERENCES basics_orders(id) ON DELETE CASCADE,
    FOREIGN KEY (product_id) REFERENCES basics_products(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- Settlement records. fee/net-style snapshot pattern (mirrors cashouts'
-- fee_amount/net_amount) so a later settings change never rewrites history.
CREATE TABLE basics_payments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL,
    member_id INT NOT NULL,
    amount_due DECIMAL(10,2) NOT NULL,
    penalty_rate DECIMAL(5,4) NOT NULL DEFAULT 0,
    penalty_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
    amount_paid DECIMAL(10,2) NOT NULL DEFAULT 0,
    offense_number TINYINT UNSIGNED DEFAULT NULL,
    is_late TINYINT(1) NOT NULL DEFAULT 0,
    paid_at TIMESTAMP NULL DEFAULT NULL,
    recorded_by INT DEFAULT NULL,
    notes VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (order_id) REFERENCES basics_orders(id) ON DELETE CASCADE,
    FOREIGN KEY (member_id) REFERENCES basics_members(id) ON DELETE CASCADE,
    FOREIGN KEY (recorded_by) REFERENCES basics_admins(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Emergency Cash Credit disbursement requests (up to emergency_credit_limit,
-- 0% interest per the program manual). A member requests an amount; admin
-- approves and records what was actually released (may differ from the
-- request if it would exceed their remaining limit) or denies it.
-- Outstanding balance is always derived (amount_released minus confirmed
-- repayments in basics_payment_submissions), not stored, so it can never
-- drift out of sync with the repayment ledger.
CREATE TABLE basics_emergency_credit_requests (
    id INT AUTO_INCREMENT PRIMARY KEY,
    member_id INT NOT NULL,
    amount_requested DECIMAL(10,2) NOT NULL,
    reason VARCHAR(255) DEFAULT NULL,
    status ENUM('pending','approved','denied') NOT NULL DEFAULT 'pending',
    amount_released DECIMAL(10,2) DEFAULT NULL,
    released_at TIMESTAMP NULL DEFAULT NULL,
    reviewed_by INT DEFAULT NULL,
    reviewed_at TIMESTAMP NULL DEFAULT NULL,
    admin_notes VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (member_id) REFERENCES basics_members(id) ON DELETE CASCADE,
    FOREIGN KEY (reviewed_by) REFERENCES basics_admins(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Member-submitted proof of payment (GCash/Bank), pending admin review.
-- Confirming a 'grocery' submission calls basics_record_payment() against
-- order_id, which is what actually writes the basics_payments ledger row —
-- this table is just the member's claim + proof, not the ledger itself.
-- 'loan' submissions repay a specific basics_emergency_credit_requests row
-- (loan_request_id) — confirming one doesn't write elsewhere, since that
-- request's outstanding balance is derived by summing confirmed repayments.
-- 'other' submissions have nothing to link to; confirming is a manual
-- admin acknowledgement only.
CREATE TABLE basics_payment_submissions (
    id INT AUTO_INCREMENT PRIMARY KEY,
    member_id INT NOT NULL,
    payment_for ENUM('grocery','loan','other') NOT NULL,
    order_id INT DEFAULT NULL,
    loan_request_id INT DEFAULT NULL,
    payment_method ENUM('gcash','bank') NOT NULL,
    destination_account VARCHAR(150) NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    reference_number VARCHAR(100) NOT NULL,
    paid_at DATETIME NOT NULL,
    proof_image VARCHAR(255) DEFAULT NULL,
    status ENUM('pending','confirmed','rejected') NOT NULL DEFAULT 'pending',
    admin_notes VARCHAR(255) DEFAULT NULL,
    reviewed_by INT DEFAULT NULL,
    reviewed_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (member_id) REFERENCES basics_members(id) ON DELETE CASCADE,
    FOREIGN KEY (order_id) REFERENCES basics_orders(id) ON DELETE SET NULL,
    FOREIGN KEY (loan_request_id) REFERENCES basics_emergency_credit_requests(id) ON DELETE SET NULL,
    FOREIGN KEY (reviewed_by) REFERENCES basics_admins(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Phase 2 benefit programs (program manual section 10): Electric Bill Cash
-- Subsidy, Hospital Financial Assistance, Burial Financial Assistance, Baon
-- Eskwela Subsidy — one shared request table for all four, like cashouts.
-- amount_due is what the member's bill/document shows; amount_paid is set
-- by the admin on approval (may be less, per program caps/fund availability).
-- relationship_to_deceased/deceased_address only apply to burial_assistance.
CREATE TABLE basics_benefit_requests (
    id INT AUTO_INCREMENT PRIMARY KEY,
    member_id INT NOT NULL,
    benefit_type ENUM('electric_subsidy','hospital_assistance','burial_assistance','baon_eskwela') NOT NULL,
    amount_due DECIMAL(10,2) NOT NULL,
    amount_paid DECIMAL(10,2) DEFAULT NULL,
    due_date DATE DEFAULT NULL,
    relationship_to_deceased VARCHAR(100) DEFAULT NULL,
    deceased_address VARCHAR(255) DEFAULT NULL,
    status ENUM('pending','approved','denied') NOT NULL DEFAULT 'pending',
    admin_notes VARCHAR(255) DEFAULT NULL,
    reviewed_by INT DEFAULT NULL,
    reviewed_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (member_id) REFERENCES basics_members(id) ON DELETE CASCADE,
    FOREIGN KEY (reviewed_by) REFERENCES basics_admins(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Supporting documents per benefit request — which doc_types are required
-- depends on benefit_type (see basics_benefit_doc_requirements() in
-- basics/includes/functions.php). Not publicly servable — see
-- uploads/basics_benefit_docs/.htaccess and basics/admin/benefit_document_view.php.
CREATE TABLE basics_benefit_documents (
    id INT AUTO_INCREMENT PRIMARY KEY,
    request_id INT NOT NULL,
    doc_type ENUM('electric_bill','medical_abstract','hospital_bill','prescription','death_certificate','enrollment_form','child_id','birth_certificate') NOT NULL,
    file_path VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (request_id) REFERENCES basics_benefit_requests(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Where a member's benefit payouts (and other receivables) get sent.
-- One record per member, self-service, editable any time.
CREATE TABLE basics_payout_accounts (
    id INT AUTO_INCREMENT PRIMARY KEY,
    member_id INT NOT NULL UNIQUE,
    method ENUM('gotyme','gcash','bank') NOT NULL,
    bank_name VARCHAR(100) DEFAULT NULL,
    account_name VARCHAR(150) NOT NULL,
    account_number VARCHAR(50) NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (member_id) REFERENCES basics_members(id) ON DELETE CASCADE
) ENGINE=InnoDB;

